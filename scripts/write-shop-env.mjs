import { writeFileSync } from 'node:fs';
import { resolveFirebaseConfig } from './shop-env-resolve.mjs';
import defaults from '../src/littleRockDefaults.json' with { type: 'json' };

function clean(name) {
  const value = process.env[name];
  return value == null ? '' : String(value).trim();
}

function validHex(value) {
  return /^#[0-9a-fA-F]{6}$/.test(value || '') ? value.toLowerCase() : '';
}

const shopName = clean('REACT_APP_SHOP_NAME');
const shopId = clean('REACT_APP_SHOP_ID');
const shopShortName = clean('REACT_APP_SHOP_SHORT_NAME');
const tagline = clean('REACT_APP_SHOP_TAGLINE');
const accent = clean('REACT_APP_SHOP_ACCENT_COLOR');
const locationLabel = clean('REACT_APP_SHOP_LOCATION_LABEL');
const appTitle = clean('REACT_APP_APP_TITLE');
const logoUrl = clean('REACT_APP_SHOP_LOGO_URL');
const brandingTouched = Boolean(
  shopName || shopId || shopShortName || tagline || accent || locationLabel || appTitle || logoUrl,
);
const resolved = resolveFirebaseConfig({
  apiKey: clean('REACT_APP_FIREBASE_API_KEY'),
  authDomain: clean('REACT_APP_FIREBASE_AUTH_DOMAIN'),
  projectId: clean('REACT_APP_FIREBASE_PROJECT_ID'),
  storageBucket: clean('REACT_APP_FIREBASE_STORAGE_BUCKET'),
  messagingSenderId: clean('REACT_APP_FIREBASE_MESSAGING_SENDER_ID'),
  appId: clean('REACT_APP_FIREBASE_APP_ID'),
  databaseURL: clean('REACT_APP_FIREBASE_DATABASE_URL'),
}, { brandingTouched, fallback: defaults.firebase });

const generated = {
  shopName: shopName || defaults.shop.shopName,
  shopNameWasSet: Boolean(shopName),
  shopId,
  shopShortName,
  tagline: tagline || defaults.shop.tagline,
  accentColor: validHex(accent) || defaults.shop.accentColor,
  locationLabel: locationLabel || defaults.shop.locationLabel,
  appTitle: appTitle || shopName || '',
  logoUrl,
  fallbackShopId: defaults.shop.shopId,
  fallbackShortName: defaults.shop.shopShortName,
  littleRockPageTitle: defaults.shop.pageTitle,
  firebaseConfig: resolved.firebaseConfig,
  firebaseConfigError: resolved.firebaseConfigError,
};

const out = process.argv[2] || new URL('../src/generatedShopEnv.js', import.meta.url);
const body = `/* Generated by scripts/write-shop-env.mjs. Do not edit. */
export const generatedShop = ${JSON.stringify(generated, null, 2)};
`;
writeFileSync(out, body);
